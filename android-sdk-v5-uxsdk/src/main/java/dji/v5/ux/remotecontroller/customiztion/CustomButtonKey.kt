/**
 * Custom Button key for each of the custom buttons on the RC, which are used to store the
 * corresponding actions in the DataStore.
 */
enum class CustomButtonKey {
    KEY_C1,
    KEY_C2,
    KEY_C3,
    KEY_5D_UP,
    KEY_5D_DOWN,
    KEY_5D_LEFT,
    KEY_5D_RIGHT,
}